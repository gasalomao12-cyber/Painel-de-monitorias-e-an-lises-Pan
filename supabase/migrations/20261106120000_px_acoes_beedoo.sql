-- Controle de ações por carteira e formalização de feedbacks no Beedoo. Pode rodar de novo sem erro.

-- 1) Cada ação guarda a carteira (as linhas sem operador, como as importadas das planilhas, também)
alter table public.px_actions add column if not exists portfolio text;
update public.px_actions a set portfolio = coalesce(o.portfolio, 'PAN')
  from public.px_operators o where a.portfolio is null and o.id = a.operator_id;
update public.px_actions set portfolio = 'PAN' where portfolio is null;
create index if not exists px_actions_portfolio_idx on public.px_actions (portfolio, action_date desc);
alter table public.px_actions drop constraint if exists px_actions_source_check;
alter table public.px_actions add constraint px_actions_source_check
  check (source in ('feedback','analise','ia','contestacao','manual','planilha','beedoo'));

create or replace view public.px_v_actions with (security_invoker = true) as
SELECT a.id,
    a.created_at,
    a.action_date,
    a.operator_id,
    a.login,
    a.segment_label,
    a.theme,
    a.action,
    a.obs,
    a.responsible,
    a.responsible_user,
    a.source,
    a.evaluation_id,
    a.feedback_id,
    a.contest_id,
    a.dedupe_key,
    a.sync_status,
    a.sync_error,
    a.sync_attempts,
    a.sync_started_at,
    a.synced_at,
    o.name AS operator_name,
    o.team,
    o.supervisor_user_id,
    o.supervisor_name,
    p.name AS responsible_name,
    p.display_name AS responsible_display,
    e.protocol,
    e.product,
    e.segment, coalesce(a.portfolio, o.portfolio, 'PAN') AS portfolio
   FROM px_actions a
     LEFT JOIN px_operators o ON o.id = a.operator_id
     LEFT JOIN px_profiles p ON p.id = a.responsible_user
     LEFT JOIN px_evaluations e ON e.id = a.evaluation_id;

-- 2) Mensagens para o Beedoo: revisadas na plataforma e enviadas pelo agente PX Beedoo
create table if not exists public.px_beedoo_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  portfolio text not null default 'PAN',
  kind text not null default 'feedback' check (kind in ('feedback','monitoria','queda','acao')),
  source_id bigint,
  operator_id bigint references public.px_operators(id) on delete set null,
  login text not null,
  operator_name text,
  message text not null,
  attachments jsonb not null default '[]'::jsonb,
  status text not null default 'pendente' check (status in ('pendente','enviando','enviado','erro','cancelado','manual')),
  error text,
  attempts integer not null default 0,
  claimed_at timestamptz,
  sent_at timestamptz,
  created_by uuid references public.px_profiles(id) on delete set null,
  agent_id bigint
);
create index if not exists px_beedoo_status_idx on public.px_beedoo_messages (created_by, status, created_at);
create index if not exists px_beedoo_source_idx on public.px_beedoo_messages (kind, source_id);

-- Chaves do agente (só o hash fica no banco); cada pessoa tem a sua
create table if not exists public.px_beedoo_agents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.px_profiles(id) on delete cascade,
  name text,
  key_hash text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz,
  revoked_at timestamptz
);

alter table public.px_beedoo_messages enable row level security;
alter table public.px_beedoo_agents enable row level security;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant all on public.px_beedoo_messages, public.px_beedoo_agents to service_role;
    grant usage, select on all sequences in schema public to service_role;
  end if;
end $$;

