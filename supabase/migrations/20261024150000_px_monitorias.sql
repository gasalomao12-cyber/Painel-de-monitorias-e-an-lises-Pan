-- PX Monitorias & Feedbacks — esquema no Supabase
-- Todas as tabelas usam o prefixo px_ para conviver com outros apps no mesmo projeto
-- (ex.: o simulador de negociação). O acesso é feito só pelo servidor, com a chave
-- secreta (service_role): RLS ligado e nenhuma policy para anon/authenticated,
-- então a chave publicável no navegador não lê nem grava nada destas tabelas.

-- ---------------------------------------------------------------- Perfis
create table if not exists public.px_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null,
  display_name text,
  role text not null check (role in ('admin','qualidade','supervisor')),
  must_change_password boolean not null default true,
  onboarded boolean not null default false,
  active boolean not null default true,
  theme text not null default 'dark',
  created_at timestamptz not null default now(),
  last_login timestamptz
);
create unique index if not exists px_profiles_email_idx on public.px_profiles (lower(email));

-- ---------------------------------------------------------------- Cadastros
create table if not exists public.px_cycles (
  id bigint generated by default as identity primary key,
  name text not null,
  start_date date not null,
  end_date date not null,
  audio_folder_url text,
  status text not null default 'aberto' check (status in ('aberto','publicado','encerrado')),
  published_at timestamptz,
  is_demo boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.px_operators (
  id bigint generated by default as identity primary key,
  name text not null,
  registration text,
  team text,
  supervisor_user_id uuid references public.px_profiles(id) on delete set null,
  supervisor_name text,
  active boolean not null default true,
  is_demo boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.px_criteria (
  id bigint generated by default as identity primary key,
  product text not null check (product in ('REFIN','ENTREGA','AMBOS')),
  code text not null,
  name text not null,
  description text,
  weight numeric not null default 1,
  critical boolean not null default false,
  sort integer not null default 0,
  active boolean not null default true
);

-- ---------------------------------------------------------------- Monitorias
create table if not exists public.px_evaluations (
  id bigint generated by default as identity primary key,
  cycle_id bigint references public.px_cycles(id) on delete set null,
  operator_id bigint not null references public.px_operators(id) on delete cascade,
  product text not null check (product in ('REFIN','ENTREGA')),
  call_date date,
  protocol text,
  contract text,
  customer text,
  duration_sec integer,
  audio_url text,
  speech_score numeric,
  final_score numeric,
  speech_summary text,
  status text not null default 'pendente' check (status in ('pendente','revisada','feedback_aplicado')),
  transcript text,
  transcript_name text,
  ai_status text not null default 'nao_executada',
  ai_summary jsonb,
  ai_model text,
  ai_ran_at timestamptz,
  reviewed_by uuid references public.px_profiles(id) on delete set null,
  reviewed_at timestamptz,
  is_demo boolean not null default false,
  created_by uuid references public.px_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists px_evaluations_cycle_idx on public.px_evaluations (cycle_id);
create index if not exists px_evaluations_operator_idx on public.px_evaluations (operator_id);
create index if not exists px_evaluations_call_date_idx on public.px_evaluations (call_date desc);

create table if not exists public.px_evaluation_items (
  id bigint generated by default as identity primary key,
  evaluation_id bigint not null references public.px_evaluations(id) on delete cascade,
  criterion_id bigint not null references public.px_criteria(id) on delete cascade,
  speech_result text check (speech_result in ('C','P','NC','NA')),
  speech_note text,
  final_result text check (final_result in ('C','P','NC','NA')),
  adjusted boolean not null default false,
  adjust_reason text,
  adjust_source text,
  adjusted_by uuid references public.px_profiles(id) on delete set null,
  adjusted_at timestamptz,
  ai_result text check (ai_result in ('C','P','NC','NA')),
  ai_evidence text,
  ai_reason text,
  ai_confidence numeric,
  unique (evaluation_id, criterion_id)
);
create index if not exists px_items_eval_idx on public.px_evaluation_items (evaluation_id);

create table if not exists public.px_feedbacks (
  id bigint generated by default as identity primary key,
  evaluation_id bigint not null references public.px_evaluations(id) on delete cascade,
  operator_id bigint not null references public.px_operators(id) on delete cascade,
  applied_by uuid references public.px_profiles(id) on delete set null,
  applied_at timestamptz not null default now(),
  modality text,
  content text not null,
  strengths text,
  improvements text,
  action_plan text,
  operator_ack boolean not null default false,
  followup_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists px_feedbacks_eval_idx on public.px_feedbacks (evaluation_id, applied_at desc);

-- ---------------------------------------------------------------- Apoio
create table if not exists public.px_bugs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.px_profiles(id) on delete set null,
  title text not null,
  description text not null,
  severity text not null default 'media',
  page text,
  user_agent text,
  screenshot text,
  status text not null default 'aberto' check (status in ('aberto','em_analise','resolvido','descartado')),
  admin_notes text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.px_audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references public.px_profiles(id) on delete set null,
  action text not null,
  entity text,
  entity_id bigint,
  detail jsonb,
  created_at timestamptz not null default now()
);
create index if not exists px_audit_entity_idx on public.px_audit_log (entity, entity_id);

create table if not exists public.px_settings (
  key text primary key,
  value text
);

create table if not exists public.px_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.px_profiles(id) on delete cascade,
  title text not null,
  body text,
  link text,
  read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists px_notifications_user_idx on public.px_notifications (user_id, read);

-- ---------------------------------------------------------------- Views de leitura
create or replace view public.px_v_eval_cards with (security_invoker = true) as
select e.id, e.cycle_id, e.operator_id, e.product, e.call_date, e.protocol, e.contract, e.customer, e.duration_sec,
       e.speech_score, e.final_score, e.status, e.ai_status, e.reviewed_at, e.created_at, e.updated_at, e.audio_url,
       c.audio_folder_url as cycle_audio_url, c.name as cycle_name, c.start_date as cycle_start,
       coalesce(nullif(e.audio_url, ''), c.audio_folder_url) as audio_link,
       (e.transcript is not null and e.transcript <> '') as has_transcript,
       o.name as operator_name, o.registration, o.team, o.supervisor_name, o.supervisor_user_id,
       coalesce(s.adjustments, 0) as adjustments, coalesce(s.ai_divergences, 0) as ai_divergences,
       coalesce(s.nc_count, 0) as nc_count, coalesce(s.c_count, 0) as c_count, coalesce(s.p_count, 0) as p_count,
       coalesce(s.critical_fail, 0) as critical_fail,
       fb.id as feedback_id, fb.applied_at as feedback_at, fb.by_display as feedback_by_display, fb.by_name as feedback_by
from public.px_evaluations e
join public.px_operators o on o.id = e.operator_id
left join public.px_cycles c on c.id = e.cycle_id
left join lateral (
  select count(*) filter (where i.adjusted)::int as adjustments,
         count(*) filter (where i.ai_result is not null and i.ai_result is distinct from i.speech_result)::int as ai_divergences,
         count(*) filter (where i.final_result = 'NC')::int as nc_count,
         count(*) filter (where i.final_result = 'C')::int as c_count,
         count(*) filter (where i.final_result = 'P')::int as p_count,
         count(*) filter (where i.final_result = 'NC' and cr.critical)::int as critical_fail
  from public.px_evaluation_items i join public.px_criteria cr on cr.id = i.criterion_id
  where i.evaluation_id = e.id
) s on true
left join lateral (
  select f.id, f.applied_at, p.display_name as by_display, p.name as by_name
  from public.px_feedbacks f left join public.px_profiles p on p.id = f.applied_by
  where f.evaluation_id = e.id order by f.applied_at desc limit 1
) fb on true;

create or replace view public.px_v_item_facts with (security_invoker = true) as
select i.id, i.evaluation_id, i.speech_result, i.final_result, i.adjusted, i.adjust_source,
       cr.id as criterion_id, cr.code, cr.name, cr.critical, cr.product as criterion_product, cr.sort,
       e.cycle_id, e.product, e.operator_id, e.status, e.final_score, e.call_date, e.protocol, e.customer, e.contract,
       o.team, o.supervisor_user_id, o.name as operator_name, o.registration
from public.px_evaluation_items i
join public.px_criteria cr on cr.id = i.criterion_id
join public.px_evaluations e on e.id = i.evaluation_id
join public.px_operators o on o.id = e.operator_id;

create or replace view public.px_v_eval_items with (security_invoker = true) as
select i.*, cr.code, cr.name, cr.description, cr.weight, cr.critical, cr.product as criterion_product, cr.sort,
       p.display_name as adjusted_by_display, p.name as adjusted_by_name
from public.px_evaluation_items i
join public.px_criteria cr on cr.id = i.criterion_id
left join public.px_profiles p on p.id = i.adjusted_by;

create or replace view public.px_v_feedbacks with (security_invoker = true) as
select f.*, o.name as operator_name, o.team, o.registration, o.supervisor_user_id,
       e.product, e.call_date, e.protocol, e.final_score, e.speech_score, e.cycle_id, c.name as cycle_name,
       p.name as applied_by_name, p.display_name as applied_by_display, p.role as applied_by_role
from public.px_feedbacks f
join public.px_evaluations e on e.id = f.evaluation_id
join public.px_operators o on o.id = f.operator_id
left join public.px_cycles c on c.id = e.cycle_id
left join public.px_profiles p on p.id = f.applied_by;

create or replace view public.px_v_audit with (security_invoker = true) as
select a.*, p.name as user_name, p.display_name as user_display
from public.px_audit_log a left join public.px_profiles p on p.id = a.user_id;

create or replace view public.px_v_bugs with (security_invoker = true) as
select b.id, b.user_id, b.title, b.description, b.severity, b.page, b.user_agent, b.status, b.admin_notes, b.created_at, b.resolved_at,
       (b.screenshot is not null) as has_screenshot, p.name as user_name, p.display_name as user_display
from public.px_bugs b left join public.px_profiles p on p.id = b.user_id;

-- ---------------------------------------------------------------- Segurança
do $$
declare t text;
begin
  foreach t in array array['px_profiles','px_cycles','px_operators','px_criteria','px_evaluations','px_evaluation_items',
                           'px_feedbacks','px_bugs','px_audit_log','px_settings','px_notifications'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
  foreach t in array array['px_v_eval_cards','px_v_item_facts','px_v_eval_items','px_v_feedbacks','px_v_audit','px_v_bugs'] loop
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to service_role', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to service_role;

notify pgrst, 'reload schema';
