-- PX Monitorias & Feedbacks — força-tarefa de análise manual das tabulações de queda de ligação.
-- px_roster: operadores do capacity (login, nome, liderança, gerência, campanha e segmento), trocado a cada
--            capacity novo; quem sai do capacity fica marcado como inativo para não perder o histórico.
-- px_roster_leaders: gerência de cada liderança (o capacity não traz a gerência).
-- px_drop_reviews: um atendimento tabulado como queda, importado do CSV de metadados ou lançado à mão,
--                  com o resultado da análise, o áudio e a transcrição anexados.
-- Pode ser executado mais de uma vez.

create table if not exists public.px_roster (
  login text primary key,              -- sempre em minúsculas
  name text not null,
  name_key text not null,              -- nome sem acento, minúsculo, para a busca
  registration text,                   -- NC
  shift text,
  status text,                         -- ATIVO, FÉRIAS, DESLIGADO, REMANEJADO…
  campaign text,                       -- campanha do mês (ATENDIMENTO IA, RECEPTIVO…)
  segment text,                        -- segmento interno (PAN LEVES, PAN MOTOS, PAN WO…)
  leader text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create index if not exists px_roster_name_idx on public.px_roster (name_key);

create table if not exists public.px_roster_leaders (
  leader text primary key,
  manager text,
  updated_at timestamptz not null default now()
);

create table if not exists public.px_drop_reviews (
  id bigint generated by default as identity primary key,
  contact_id text,                     -- IdContato do discador
  call_at timestamp,                   -- data e hora da ligação (horário local do discador)
  duration_sec integer,
  login text,
  operator_name text,
  leader text,
  manager text,
  campaign text,                       -- campanha/setor do capacity
  segment text,
  dialer_campaign text,                -- campanha do discador (ex.: APTI_PANWO_AGVIA)
  operation text,                      -- operação do discador (ex.: PAN VEICULOS)
  tabulation text,                     -- finalização feita pelo operador
  disconnect text check (disconnect in ('Interna', 'Externa')),
  contract text,
  customer text,
  audio_file text,                     -- nome do arquivo na gravação
  audio_original text,                 -- nome original do arquivo (asp-…_IdContato.wav)
  status text not null default 'pendente' check (status in ('pendente', 'analisada')),
  verdict text check (verdict in ('cliente', 'operador', 'tecnica', 'mudo', 'concluido', 'inconclusivo')),
  conduct boolean not null default false,
  conduct_type text,
  tab_correct boolean,
  correct_tab text,
  drop_moment text,                    -- mm:ss em que a ligação caiu
  notes text,
  audio_url text,                      -- link do áudio na pasta
  audio_path text,                     -- arquivo anexado (bucket px-quedas)
  audio_name text,
  transcript text,
  transcript_name text,
  analyst_id uuid references public.px_profiles(id) on delete set null,
  analyst_name text,
  analyzed_at timestamptz,
  locked_by uuid references public.px_profiles(id) on delete set null,
  locked_name text,
  locked_at timestamptz,
  batch text,
  created_by uuid references public.px_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- Índice único sem filtro (para o ON CONFLICT); lançamentos sem IdContato (NULL) nunca conflitam
create unique index if not exists px_drop_reviews_contact_idx on public.px_drop_reviews (contact_id);
create index if not exists px_drop_reviews_call_idx on public.px_drop_reviews (call_at desc);
create index if not exists px_drop_reviews_login_idx on public.px_drop_reviews (login);

alter table public.px_roster enable row level security;
alter table public.px_roster_leaders enable row level security;
alter table public.px_drop_reviews enable row level security;
revoke all on public.px_roster, public.px_roster_leaders, public.px_drop_reviews from anon, authenticated;
grant all on public.px_roster, public.px_roster_leaders, public.px_drop_reviews to service_role;
grant usage, select on all sequences in schema public to service_role;

do $$
declare t text;
begin
  foreach t in array array['px_roster', 'px_roster_leaders', 'px_drop_reviews'] loop
    execute format('drop trigger if exists px_broadcast on public.%I', t);
    execute format('create trigger px_broadcast after insert or update or delete on public.%I
                    for each statement execute function public.px_broadcast_change()', t);
  end loop;
end $$;

-- Áudios anexados às análises: bucket privado, lido só pelo servidor (link assinado de poucos minutos)
insert into storage.buckets (id, name, public, file_size_limit)
values ('px-quedas', 'px-quedas', false, 52428800)
on conflict (id) do nothing;

-- O link da pasta de áudios (px_settings.drop_audio_folder) é salvo pela própria aba, só no banco.

notify pgrst, 'reload schema';
