-- PX Monitorias & Feedbacks — contestação de monitorias.
-- A supervisão pede a revisão de uma monitoria (com motivo e, se quiser, os itens contestados);
-- a Qualidade aceita (e ajusta a análise) ou recusa, sempre com resposta registrada.
-- Pode ser executado mais de uma vez.

create table if not exists public.px_contests (
  id bigint generated by default as identity primary key,
  evaluation_id bigint not null references public.px_evaluations(id) on delete cascade,
  requested_by uuid references public.px_profiles(id) on delete set null,
  reason text not null,
  criteria jsonb not null default '[]',          -- [{ criterion_id, code, name }] contestados
  status text not null default 'aberta' check (status in ('aberta','aceita','recusada','cancelada')),
  response text,
  responded_by uuid references public.px_profiles(id) on delete set null,
  responded_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists px_contests_eval_idx on public.px_contests (evaluation_id, created_at desc);
create index if not exists px_contests_status_idx on public.px_contests (status);
-- Uma contestação aberta por vez em cada monitoria
create unique index if not exists px_contests_open_idx on public.px_contests (evaluation_id) where status = 'aberta';

create or replace view public.px_v_contests with (security_invoker = true) as
select ct.*, e.product, e.segment, e.call_date, e.protocol, e.final_score, e.cycle_id, e.operator_id, e.status as evaluation_status,
       o.name as operator_name, o.team, o.supervisor_user_id, o.supervisor_name,
       rq.name as requested_by_name, rq.display_name as requested_by_display,
       rs.name as responded_by_name, rs.display_name as responded_by_display
from public.px_contests ct
join public.px_evaluations e on e.id = ct.evaluation_id
join public.px_operators o on o.id = e.operator_id
left join public.px_profiles rq on rq.id = ct.requested_by
left join public.px_profiles rs on rs.id = ct.responded_by;

alter table public.px_contests enable row level security;
revoke all on public.px_contests, public.px_v_contests from anon, authenticated;
grant all on public.px_contests to service_role;
grant select on public.px_v_contests to service_role;
grant usage, select on all sequences in schema public to service_role;

