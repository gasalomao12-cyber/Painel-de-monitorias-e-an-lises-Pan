-- Análises da carteira: relatórios em HTML (ex.: Conversão e Eficiência) com os dados extraídos
create table if not exists public.px_reports (
  id bigint generated by default as identity primary key,
  portfolio text not null default 'PAN',
  kind text not null,
  title text not null,
  period text,
  file_name text,
  data jsonb not null default '{}'::jsonb,
  html text,
  created_by uuid references public.px_profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists px_reports_portfolio_idx on public.px_reports (portfolio, created_at desc);
alter table public.px_reports enable row level security;
-- No Supabase a API usa o service_role; no PostgreSQL da empresa (sem esse papel) não há o que conceder
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant all on public.px_reports to service_role;
    grant usage, select on all sequences in schema public to service_role;
  end if;
end $$;

