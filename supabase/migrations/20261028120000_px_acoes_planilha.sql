-- PX Monitorias & Feedbacks — registro das ações (feedbacks, análises, calibragens, ações manuais)
-- e envio automático, linha a linha, para a planilha online "CONTROLE DE AÇÕES".
-- Cada linha já guarda as colunas da planilha (LOGIN, SEGMENTO, TEMA, AÇÃO, DATA, OBS, RESPONSÁVEL)
-- e o status do envio, para reenviar o que falhar sem duplicar.
-- Pode ser executado mais de uma vez.

create table if not exists public.px_actions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  action_date date not null default current_date,
  operator_id bigint references public.px_operators(id) on delete set null,
  login text,
  segment_label text,
  theme text,
  action text not null,
  obs text,
  responsible text,
  responsible_user uuid references public.px_profiles(id) on delete set null,
  source text not null default 'manual' check (source in ('feedback','analise','ia','contestacao','manual')),
  evaluation_id bigint references public.px_evaluations(id) on delete set null,
  feedback_id bigint references public.px_feedbacks(id) on delete set null,
  contest_id bigint references public.px_contests(id) on delete set null,
  dedupe_key text,
  sync_status text not null default 'pendente' check (sync_status in ('pendente','enviando','enviado','erro','ignorado')),
  sync_error text,
  sync_attempts integer not null default 0,
  sync_started_at timestamptz,
  synced_at timestamptz
);
-- Índice único sem filtro (para o ON CONFLICT); linhas sem chave (NULL) nunca conflitam
drop index if exists public.px_actions_dedupe_idx;
create unique index px_actions_dedupe_idx on public.px_actions (dedupe_key);
create index if not exists px_actions_date_idx on public.px_actions (action_date desc, id desc);
create index if not exists px_actions_sync_idx on public.px_actions (sync_status) where sync_status <> 'enviado';
create index if not exists px_actions_operator_idx on public.px_actions (operator_id);

create or replace view public.px_v_actions with (security_invoker = true) as
select a.*, o.name as operator_name, o.team, o.supervisor_user_id, o.supervisor_name,
       p.name as responsible_name, p.display_name as responsible_display,
       e.protocol, e.product, e.segment
from public.px_actions a
left join public.px_operators o on o.id = a.operator_id
left join public.px_profiles p on p.id = a.responsible_user
left join public.px_evaluations e on e.id = a.evaluation_id;

alter table public.px_actions enable row level security;
revoke all on public.px_actions, public.px_v_actions from anon, authenticated;
grant all on public.px_actions to service_role;
grant select on public.px_v_actions to service_role;
grant usage, select on all sequences in schema public to service_role;

drop trigger if exists px_broadcast on public.px_actions;
create trigger px_broadcast after insert or update or delete on public.px_actions
  for each statement execute function public.px_broadcast_change();

notify pgrst, 'reload schema';
