left join public.px_profiles p on p.id = f.applied_by;

create or replace view public.px_v_audit with (security_invoker = true) as
select a.*, p.name as user_name, p.display_name as user_display
from public.px_audit_log a left join public.px_profiles p on p.id = a.user_id;

create or replace view public.px_v_bugs with (security_invoker = true) as
select b.id, b.user_id, b.title, b.description, b.severity, b.page, b.user_agent, b.status, b.admin_notes, b.created_at, b.resolved_at,
       (b.screenshot is not null) as has_screenshot, p.name as user_name, p.display_name as user_display
